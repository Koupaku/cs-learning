// ===== 打样：展开运算符 ... 与"不可变性" =====
// 学习方法：打开页面按 F12，边看 Console 输出边读注释
// 意义：React 的核心规矩是"更新数据 = 造新的，不碰旧的"（不可变性）
//       这个打样让你提前练熟这个肌肉记忆

// ------------------------------------------------------------
// 【零件 1】为什么不能"直接改"数组？—— 别名陷阱
// ------------------------------------------------------------
const a = [1, 2, 3];
const b = a;        // 你以为在"复制"，其实 b 和 a 指向【同一个】数组
b.push(4);          // 改 b...
console.log('零件1：a 也被改了 →', a);   // a 变成了 [1,2,3,4]！因为它俩是同一个
// 在 React 里，这种"顺手改到别人"的行为会造成诡异 bug：
// 页面明明没操作 A，A 却变了 —— 因为有人通过"别名"偷偷改了它
// 所以 React 立规矩：更新就造新数组，旧的一律不碰

// ------------------------------------------------------------
// 【零件 2】展开运算符 ...：真正地"复制"数组
// ------------------------------------------------------------
const c = [1, 2, 3];
const d = [...c];   // ...c = 把 c 的元素摊开，装进一个【全新】数组
d.push(4);          // 改 d
console.log('零件2：c 没变 →', c, '| d 变了 →', d);
// ... 的读法："把数组摊开"。用途一：复制。

// React 里"添加一条"就是这么写的（先混脸熟）：
// const newTodos = [...todos, newItem];   // 旧的不动，新的 = 旧的全部 + 新条目

// ------------------------------------------------------------
// 【零件 3】复制并修改对象：{ ...obj, 改一点 }
// ------------------------------------------------------------
const todo = { id: 1, text: '买牛奶', done: false };
const updated = { ...todo, done: true };   // 先摊开旧对象的全部属性，再覆盖 done
console.log('零件3：todo 没变 →', todo);            // done 还是 false
console.log('零件3：updated 是新对象 →', updated);  // done 变 true，其他原样
// 读法："把 todo 摊开照抄一份，其中 done 改成 true"
// 注意顺序：{ ...todo, done: true } 里，后面的 done 会覆盖前面摊开来的 done

// ------------------------------------------------------------
// 【零件 4】组合拳：map + 展开 = "改其中一条"
// ------------------------------------------------------------
// 场景：把 id=1 那条的 done 翻转（练习 08 的 TODO 1 就是它）
let todos = [
  { id: 1, text: '买牛奶', done: false },
  { id: 2, text: '写作业', done: true },
];
todos = todos.map((t) => t.id === 1 ? { ...t, done: !t.done } : t);
//          逐行读：
//          t.id === 1          命中要改的那条吗？  //id === 1 的意思是 id === true 吗?
//          ? { ...t, done: !t.done }   命中 → 照抄一份，done 取反（造新的！）
//          : t                          没命中 → 原样返回（不碰）
console.log('零件4：翻转后的 todos →', todos);
// 输出的数组中，id=1 的 done 变 true，id=2 的保持原样

// ------------------------------------------------------------
// 【零件 5】预告：这就是 React 的日常
// ------------------------------------------------------------

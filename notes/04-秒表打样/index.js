// ===== 打样：秒表的核心零件 setInterval / clearInterval =====
// 使用方法：双击 index.html 打开，按 F12 看 Console
// 学习法：每个零件 = 先 console.log 演示 → 再解释 → 最后组装成秒表

// ------------------------------------------------------------
// 【零件 1】setInterval：每隔一段时间，自动执行一次函数
// ------------------------------------------------------------
// setInterval(函数, 毫秒) —— 每 1000 毫秒（1秒）执行一次函数
// 注意：它不会立刻执行，第一次要等满 1 秒才开始
// 注意：它执行起来就"停不下来"，除非你叫停（零件 2）
let count = 0;                                       // 计数器
const timer1 = setInterval(() => {                   // 启动一个每秒执行一次的计时器
  count++;                                           // 每次 +1
  console.log('零件1：滴答', count, '次');            // 打印
}, 1000);                                            // 间隔 1000 毫秒 = 1 秒
console.log('零件1：计时器已启动，编号是', timer1);   // 编号是个数字，将来靠它叫停

// ------------------------------------------------------------
// 【零件 2】clearInterval：停掉计时器
// ------------------------------------------------------------
// 规则：setInterval 返回一个"编号"，clearInterval(编号) 就能停
setTimeout(() => {                                   // setTimeout：延迟执行一次（新朋友，先混脸熟）
  clearInterval(timer1);                             // 用编号叫停零件1的计时器
  console.log('零件2：5 秒到，零件1的计时器已停止');
}, 5000);                                            // 5 秒后执行

// ------------------------------------------------------------
// 【零件 3】在页面上实时显示：秒表的显示原理
// ------------------------------------------------------------
const display = document.getElementById('display');  // 抓到页面上的数字框
let seconds = 0;                                     // 已过秒数
const timer2 = setInterval(() => {                   // 每 100 毫秒（0.1秒）动一次
  seconds = seconds + 0.1;                           // 秒数 +0.1
  display.textContent = seconds.toFixed(1) + ' 秒';   // 更新页面文字（toFixed(1)保留1位小数）
}, 100);
console.log('零件3：去看页面，数字在自动跳动 —— 秒表的核心就这么简单');

// ------------------------------------------------------------
// 【零件 4】危险示范：同一个秒表开两个计时器会怎样？
// ------------------------------------------------------------
// 先停掉零件3的计时器，从头演示
clearInterval(timer2);                               // 停掉零件3
seconds = 0;                                         // 归零
// 下面连续开两个一模一样的计时器：
setInterval(() => { seconds += 0.1; display.textContent = seconds.toFixed(1) + ' 秒'; }, 100);
setInterval(() => { seconds += 0.1; display.textContent = seconds.toFixed(1) + ' 秒'; }, 100);
// → 页面数字以 2 倍速狂飙！这就是"重复开启计时器"的 bug
// 所以秒表程序里必须先检查"是不是已经在计时了"（用 running 标志），
// 已经在计时就不要再开新的 —— 这就是练习04 TODO 1 里那句"直接 return"的原因
console.log('零件4：页面数字在 2 倍速狂飙了吧？刷新页面可以停掉');

